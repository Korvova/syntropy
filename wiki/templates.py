"""Шаблоны Синтропии в Outline: «Эпик» и «Т. Требования». Создаются как документы-шаблоны коллекции «Синтропия»,
дальше «New doc → from template». Запуск: python wiki/templates.py"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools"))
import outline

EPIC = """**Что это.** Два абзаца: что за проект, для кого, чем отличается от того, что есть. Человек, впервые открывший страницу, за минуту понимает, что это и куда смотреть дальше.

**Зачем.** Какое решение или результат проект должен дать и по какому признаку поймём, что получилось.

## Текущее состояние

| Узел | Состояние |
|---|---|
| Узел 1 | ⬜ Не начато |
| Узел 2 | ⬜ Не начато |

## Точки проекта

Всё, где живёт проект. Агент обходит эти точки и собирает требования, замечания и уроки в таблицы. Ключи и пароли сюда не пишем — только адреса и имена; секреты лежат в настройках агента.

| Точка | Где | Что там |
|---|---|---|
| Репозиторий | github.com/… | код, модели, эта документация в папке `wiki/` |
| Чат с ИИ | Синтропия, эпик «…» | обсуждение с агентом, откуда берутся требования |
| Группа в Telegram | @… | замечания сборщиков, фото с места |
| Битрикс24 | группа «…», задачи | задачи и сроки |
| Модели | SolidWorks, папка … | детали, сборки, чертежи |

## Команда

Кто есть кто в проекте. Агент по @имени находит человека здесь и доставляет сообщение в его канал, после подтверждения.

| Имя | Роль | Битрикс24 | Telegram | Куда писать |
|---|---|---|---|---|
| … | руководитель проекта | ID … | @… | Telegram |
| … | инженер-конструктор | ID … | @… | Битрикс |

## Оглавление

* [Т. Требования](#) — таблица требований по разделам
* [Т. Закупки](#) — покупные изделия, цены, итог
* [Т. Этапы работ](#) — этапы с результатом и проверкой
* Техническая документация — архитектура, развёртывание, протоколы

## Правила

Новая правка — новая строка. Строки не удаляются: отменённое получает статус ❌ Исключено с причиной. Уроки пишем сразу. Статус в названии страницы — про страницу целиком, статус в таблице — про строку.
"""

TREQ = """Раздел требований проекта. Одна строка — одно требование, одна проверка. Нумерация — по ТЗ или сквозная по проекту.

## Этап 1. Название этапа

| Номер | Требование | Описание | Урок | Статус |
|---|---|---|---|---|
| 1.1 | Что должно быть, до 80 символов | Как это выглядит на практике, до 250. Сюда же картинка или ссылка на файл | Грабли и неочевидное, до 300. Хеш коммита, которым закрыто | ⬜ Не начато |
| 1.2 | … | … | … | ⚠️ Частично |

## Этап 2. Название этапа

| Номер | Требование | Описание | Урок | Статус |
|---|---|---|---|---|
| 2.1 | … | … | … | ✅ Готово |

_Статусы строк: ✅ Готово · ⚠️ Частично · ⬜ Не начато · ❌ Исключено (с причиной). Не больше 25 активных строк на странице, остальное — в архив._
"""

TBUY = """Покупные изделия и материалы проекта. Одна строка — одна позиция. Итог считается по колонке «Сумма».

| Номер | Позиция | Кол-во | Цена, ₽ | Сумма, ₽ | Поставщик | Для требования | Статус |
|---|---|---|---|---|---|---|---|
| З.1 | … | 1 | 0 | 0 | … | 3.3 | ⬜ Не куплено |

**Итого:** 0 ₽

_Статусы: ⬜ Не куплено · ⌛ Заказано · ✅ Получено · ❌ Исключено. Поставщики без чека или со срывами — в урок строки._
"""

col = outline.collection("Синтропия")
def template(title, text):
    d = next((x for x in outline.api("documents.list", {"collectionId": col["id"], "template": True, "limit": 50})["data"] if x["title"] == title), None)
    if d:
        return outline.api("documents.update", {"id": d["id"], "title": title, "text": text, "publish": True})["data"]
    return outline.api("documents.create", {"collectionId": col["id"], "title": title, "text": text, "template": True, "publish": True})["data"]

for t, txt in (("Шаблон: Эпик", EPIC), ("Шаблон: Т. Требования", TREQ), ("Шаблон: Т. Закупки", TBUY)):
    print(outline.link(template(t, txt)))
